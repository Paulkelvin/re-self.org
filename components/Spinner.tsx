/**
 * Inline loading spinner for async actions (form submits). Uses Tailwind's
 * `animate-spin`; the site-wide prefers-reduced-motion rule freezes it to a
 * static ring, leaving the disabled state + label to signal progress.
 */
export function Spinner({ className = "" }: { className?: string }) {
  return (
    <svg
      className={`animate-spin ${className}`}
      width="16"
      height="16"
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
    >
      <circle cx="12" cy="12" r="9" stroke="currentColor" strokeWidth="3" className="opacity-25" />
      <path d="M21 12a9 9 0 0 0-9-9" stroke="currentColor" strokeWidth="3" strokeLinecap="round" />
    </svg>
  );
}
